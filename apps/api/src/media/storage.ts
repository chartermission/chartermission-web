import { createReadStream, createWriteStream } from 'node:fs';
import { copyFile, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { Transform } from 'node:stream';
import { DeleteObjectCommand, GetObjectCommand, HeadObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { env } from '../config/env.js';
import { hmac, safeEqual } from '../common/crypto.js';
import { Errors } from '../common/errors.js';

/** Signed upload and download URLs expire after 15 minutes (spec 6.3, proposed). */
export const URL_TTL_SECONDS = 15 * 60;

export interface PresignedUpload {
  url: string;
  headers: Record<string, string>;
}

/**
 * Object storage behind one interface (spec 6.3). Keys are generated by the API
 * (`uploads/<purpose>/<fileId>`), never taken from the client.
 */
export interface Storage {
  readonly driver: 'local' | 's3';
  presignUpload(input: { fileId: string; key: string; mime: string; sizeBytes: number; expiresAt: Date }): Promise<PresignedUpload>;
  /** Size of the stored object, or null when nothing was uploaded. */
  size(key: string): Promise<number | null>;
  /** Reads the whole object (callers check size() against the purpose limit first). */
  read(key: string): Promise<Buffer | null>;
  write(key: string, data: Buffer, mime: string): Promise<void>;
  remove(key: string): Promise<void>;
  /** s3: a signed GET URL; local: null (the API streams the file itself). */
  presignDownload(key: string, opts: { mime: string; disposition: string }): Promise<string | null>;
  /** local only: a stream of the object, or of a byte range of it (inclusive). */
  open(key: string, range?: { start: number; end: number }): Readable;
  /** Copies the object to a local file (video processing). False when nothing was uploaded. */
  downloadTo(key: string, file: string): Promise<boolean>;
  /** Stores a local file under the key, streaming (large videos). */
  uploadFrom(key: string, file: string, mime: string): Promise<void>;
}

/* ---------------- local driver ---------------- */

export function uploadSignature(fileId: string, exp: number): string {
  return hmac(`upload:${fileId}:${exp}`);
}

export function verifyUploadSignature(fileId: string, exp: number, sig: string): boolean {
  if (!Number.isFinite(exp) || exp * 1000 < Date.now()) return false;
  return safeEqual(uploadSignature(fileId, exp), sig);
}

/**
 * Development driver: files under STORAGE_LOCAL_DIR. The upload URL points at this
 * API's own PUT /uploads/{id}/blob, authorised by an HMAC signature and expiry.
 */
export class LocalStorage implements Storage {
  readonly driver = 'local' as const;
  private readonly root = path.resolve(env().STORAGE_LOCAL_DIR);

  private pathFor(key: string): string {
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }

  async presignUpload({ fileId, mime, expiresAt }: { fileId: string; mime: string; expiresAt: Date }) {
    const exp = Math.floor(expiresAt.getTime() / 1000);
    const base = env().API_PUBLIC_URL.replace(/\/$/, '');
    const url = `${base}/uploads/${fileId}/blob?exp=${exp}&sig=${uploadSignature(fileId, exp)}`;
    return { url, headers: { 'Content-Type': mime } };
  }

  /** Streams a request body to disk, aborting as soon as it exceeds maxBytes. Returns bytes written. */
  async receive(key: string, body: Readable, maxBytes: number): Promise<number> {
    const target = this.pathFor(key);
    await mkdir(path.dirname(target), { recursive: true });
    const partial = `${target}.part`;
    let total = 0;
    const limiter = new Transform({
      transform(chunk: Buffer, _enc, cb) {
        total += chunk.length;
        if (total > maxBytes) cb(Errors.tooLarge('The file is larger than allowed'));
        else cb(null, chunk);
      },
    });
    try {
      await pipeline(body, limiter, createWriteStream(partial));
    } catch (err) {
      await rm(partial, { force: true });
      throw err;
    }
    await rename(partial, target);
    return total;
  }

  async size(key: string) {
    try {
      return (await stat(this.pathFor(key))).size;
    } catch {
      return null;
    }
  }

  async read(key: string) {
    try {
      return await readFile(this.pathFor(key));
    } catch {
      return null;
    }
  }

  async write(key: string, data: Buffer) {
    const target = this.pathFor(key);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, data);
  }

  async remove(key: string) {
    await rm(this.pathFor(key), { force: true });
  }

  presignDownload(): Promise<string | null> {
    return Promise.resolve(null);
  }

  open(key: string, range?: { start: number; end: number }): Readable {
    return createReadStream(this.pathFor(key), range);
  }

  async downloadTo(key: string, file: string) {
    try {
      await copyFile(this.pathFor(key), file);
      return true;
    } catch {
      return false;
    }
  }

  async uploadFrom(key: string, file: string) {
    const target = this.pathFor(key);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(file, target);
  }
}

/* ---------------- s3 driver ---------------- */

/**
 * Only send and check checksums when an operation requires them. Since @aws-sdk/client-s3 3.729 the
 * default ("WHEN_SUPPORTED") signs a CRC32 of an *empty* body into presigned PUT URLs and adds
 * x-amz-checksum-mode to presigned GETs, so R2 rejected every browser upload. Cloudflare's R2 guide
 * for this SDK sets both options to WHEN_REQUIRED.
 */
export const S3_COMPAT = { requestChecksumCalculation: 'WHEN_REQUIRED', responseChecksumValidation: 'WHEN_REQUIRED' } as const;

/** Any S3-compatible bucket (Cloudflare R2, Railway buckets, AWS S3) via S3_ENDPOINT. Private bucket. */
export class S3Storage implements Storage {
  readonly driver = 's3' as const;
  private readonly client: S3Client;
  private readonly bucket: string;

  constructor() {
    const e = env();
    if (!e.S3_BUCKET) throw new Error('S3_BUCKET must be set when STORAGE_DRIVER=s3');
    this.bucket = e.S3_BUCKET;
    this.client = new S3Client({
      region: e.S3_REGION,
      endpoint: e.S3_ENDPOINT,
      forcePathStyle: !!e.S3_ENDPOINT,
      ...S3_COMPAT,
      credentials:
        e.S3_ACCESS_KEY_ID && e.S3_SECRET_ACCESS_KEY
          ? { accessKeyId: e.S3_ACCESS_KEY_ID, secretAccessKey: e.S3_SECRET_ACCESS_KEY }
          : undefined,
    });
  }

  async presignUpload({ key, mime, sizeBytes }: { key: string; mime: string; sizeBytes: number }) {
    // ContentLength is signed, so the bucket rejects a body of any other size.
    const command = new PutObjectCommand({ Bucket: this.bucket, Key: key, ContentType: mime, ContentLength: sizeBytes });
    const url = await getSignedUrl(this.client, command, { expiresIn: URL_TTL_SECONDS });
    return { url, headers: { 'Content-Type': mime } };
  }

  async size(key: string) {
    try {
      const head = await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
      return head.ContentLength ?? 0;
    } catch {
      return null;
    }
  }

  async read(key: string) {
    try {
      const obj = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      if (!obj.Body) return null;
      return Buffer.from(await obj.Body.transformToByteArray());
    } catch {
      return null;
    }
  }

  async write(key: string, data: Buffer, mime: string) {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: mime }));
  }

  async remove(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }

  async presignDownload(key: string, opts: { mime: string; disposition: string }) {
    const command = new GetObjectCommand({
      Bucket: this.bucket,
      Key: key,
      ResponseContentType: opts.mime,
      ResponseContentDisposition: opts.disposition,
      ResponseCacheControl: 'private, max-age=900',
    });
    return getSignedUrl(this.client, command, { expiresIn: URL_TTL_SECONDS });
  }

  open(): Readable {
    throw new Error('S3 objects are served through signed URLs');
  }

  async downloadTo(key: string, file: string) {
    let obj;
    try {
      obj = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    } catch (err) {
      // Only a missing object means "not uploaded"; network or permission errors retry the job.
      const name = (err as { name?: string; $metadata?: { httpStatusCode?: number } }).name;
      if (name === 'NoSuchKey' || (err as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode === 404) return false;
      throw err;
    }
    if (!obj.Body) return false;
    await pipeline(obj.Body as Readable, createWriteStream(file));
    return true;
  }

  async uploadFrom(key: string, file: string, mime: string) {
    const { size } = await stat(file);
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: createReadStream(file), ContentType: mime, ContentLength: size }),
    );
  }
}

export function createStorage(): Storage {
  return env().STORAGE_DRIVER === 's3' ? new S3Storage() : new LocalStorage();
}
