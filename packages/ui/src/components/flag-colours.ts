/** Brand palette for countries without flag colours (stable per code). */
const BRAND_SETS = [
  ["#0A8A47", "#FF9A1F", "#ED0918"],
  ["#F59E0B", "#FFFFFF", "#0A8A47"],
  ["#ED0918", "#FF9A1F", "#FFFFFF"],
  ["#FFFFFF", "#0A8A47", "#F59E0B"],
];

export function flagColours(countryCode: string | null | undefined): string[] {
  const code = (countryCode ?? "").toUpperCase();
  const known = FLAG_COLOURS[code];
  if (known) return known;
  let h = 0;
  for (const ch of code) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return BRAND_SETS[h % BRAND_SETS.length]!;
}
